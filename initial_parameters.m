function p = initial_parameters()

%==================================================
% GEOMETRY
%==================================================

p.H = 0.60;            % Bed height (m)

p.N = 61;              % Grid points

p.dz = p.H/(p.N-1);

%==================================================
% TIME
%==================================================

p.dt = 0.01;

p.t_end = 1200;

%==================================================
% SOLID PHASE
%==================================================

p.rhos = 1500;         % kg/m3

p.Cps = 1000;          % J/kg-K

p.ks = 3;            % W/m-K

%==================================================
% GAS PHASE
%==================================================

p.rhog = 1.2;          % kg/m3

p.Cpg = 1000;          % J/kg-K

p.hgs = 2000;            % W/m2-K
%==================================================
% BED POROSITY
%==================================================

p.eps = 0.35;

%==================================================
% GAS CONDUCTIVITY
%==================================================

p.kg = 0.10;

%==================================================
% SUCTION FLOW
%==================================================

p.ug = 0.30;           % m/s downward gas velocity

%==================================================
% COKE
%==================================================

p.coke_fraction = 0.04;

%==================================================
% COMBUSTION
%==================================================

p.k0 = 0.05;

p.E = 25000;

p.Rg = 8.314;

p.deltaH = 5.0e7;

p.Tignite = 600;

%==================================================
% IGNITION
%==================================================

p.Tignition = 1200;

%==================================================
% COKE DENSITY
%==================================================

p.rhocoke = 500;      % kg/m3 coke

%==================================================
% MOLECULAR WEIGHTS
%==================================================

p.MW_C = 12;

p.MW_O2 = 32;

%==================================================
% OXYGEN REQUIREMENT
% kg O2/kg C
%==================================================

p.O2_stoich = p.MW_O2/p.MW_C;

% = 2.667
p.MW_CO2 = 44;

p.CO2_stoich = p.MW_CO2/p.MW_C;

%==================================================
% MOISTURE
%==================================================

p.M0 = 0.08;

p.lambda_evap = 2.26e6;    % J/kg

p.Tevap = 373;             % K

end