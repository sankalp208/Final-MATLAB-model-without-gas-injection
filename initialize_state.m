function state = initialize_state(p)

%==========================================
% SOLID TEMPERATURE
%==========================================

state.Ts = 300*ones(p.N,1);

%==========================================
% GAS TEMPERATURE
%==========================================

state.Tg = 300*ones(p.N,1);

%==========================================
% OXYGEN FRACTION
%==========================================

state.O2 = 0.21*ones(p.N,1);

%==========================================
% COKE DISTRIBUTION
%==========================================

state.Coke = p.coke_fraction*ones(p.N,1);

%==========================================
% REACTION RATE
%==========================================

state.R = zeros(p.N,1);

%==========================================
% GAS VELOCITY
%==========================================

state.ug = p.ug*ones(p.N,1);

%==========================================
% IGNITION CONDITION
%==========================================

state.Ts(1) = p.Tignition;

state.Tg(1) = p.Tignition;

state.CO2 = zeros(p.N,1);

state.M = 0.08*ones(p.N,1);

end